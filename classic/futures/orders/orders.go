// GetOrderByID looks up a single order (including stop orders) by its
// KuCoin-assigned ID.
//
// Docs: https://www.kucoin.com/docs-new/rest/futures-trading/orders/get-order-by-orderld
func (c *Client) GetOrderByID(ctx context.Context, orderID string) (*Order, error) {
	var result Order
	if _, err := c.executor.Do(ctx, http.MethodGet, "/api/v1/orders/"+orderID, nil, nil, &result); err != nil {
		return nil, err
	}
	return &result, nil
}

// GetOrderListOptions are the optional filters for GetOrderList. "done"
// orders are limited to a 7-day startAt/endAt range; "active" orders have
// no time-range limit.
type GetOrderListOptions struct {
	Status      string // active, done (default done)
	Symbol      string
	Side        string // buy, sell
	Type        string // limit, market, limit_stop, market_stop, oco_limit, oco_stop
	StartAt     int64  // Unix milliseconds
	EndAt       int64  // Unix milliseconds
	CurrentPage int
	PageSize    int // default 50, max 1000
}

// GetOrderList lists orders, paginated by page number (not cursor).
//
// Docs: https://www.kucoin.com/docs-new/rest/futures-trading/orders/get-order-list
func (c *Client) GetOrderList(ctx context.Context, opts GetOrderListOptions) (*OrderListPage, error) {
	query := map[string]string{}
	if opts.Status != "" {
		query["status"] = opts.Status
	}
	if opts.Symbol != "" {
		query["symbol"] = opts.Symbol
	}
	if opts.Side != "" {
		query["side"] = opts.Side
	}
	if opts.Type != "" {
		query["type"] = opts.Type
	}
	if opts.StartAt != 0 {
		query["startAt"] = strconv.FormatInt(opts.StartAt, 10)
	}
	if opts.EndAt != 0 {
		query["endAt"] = strconv.FormatInt(opts.EndAt, 10)
	}
	if opts.CurrentPage > 0 {
		query["currentPage"] = strconv.Itoa(opts.CurrentPage)
	}
	if opts.PageSize > 0 {
		query["pageSize"] = strconv.Itoa(opts.PageSize)
	}
	var result OrderListPage
	if _, err := c.executor.Do(ctx, http.MethodGet, "/api/v1/orders", query, nil, &result); err != nil {
		return nil, err
	}
	return &result, nil
}
