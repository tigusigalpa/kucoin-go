package orders

import (
	"context"
	"errors"
	"net/http"
	"strconv"

	"github.com/tigusigalpa/kucoin-go/transport"
)

// ErrMutuallyExclusiveSize is returned locally (no network call) when
// more than one of Size/Qty/ValueQty is set on a PlaceOrderRequest.
var ErrMutuallyExclusiveSize = errors.New("kucoin: set at most one of Size, Qty, or ValueQty")

// ErrLimitOrderRequiresPrice is returned locally (no network call) when a
// non-market, non-close order has no price set.
var ErrLimitOrderRequiresPrice = errors.New("kucoin: a limit order requires Price")

// Client provides a seed set of KuCoin Classic Futures' private
// order-management endpoints. Every method requires credentials with the
// Futures (write) or General (read) permission; calls return
// transport.ErrCredentialsRequired locally (no network call) if none are
// configured.
type Client struct {
	executor *transport.Executor
}

// NewClient wires an orders.Client to the shared Classic Futures
// Executor. Not normally called directly; use kucoin.NewClient.
func NewClient(executor *transport.Executor) *Client {
	return &Client{executor: executor}
}

func validatePlaceOrder(req PlaceOrderRequest) error {
	set := 0
	if req.Size != 0 {
		set++
	}
	if req.Qty != "" {
		set++
	}
	if req.ValueQty != "" {
		set++
	}
	if set > 1 {
		return ErrMutuallyExclusiveSize
	}
	if !req.CloseOrder && (req.Type == "" || req.Type == "limit") && req.Price == "" {
		return ErrLimitOrderRequiresPrice
	}
	return nil
}

// PlaceOrder submits a new Classic Futures order. req.ClientOid is sent
// as-is (never generated by this SDK) and is required by KuCoin.
//
// Docs: https://www.kucoin.com/docs-new/rest/futures-trading/orders/add-order
func (c *Client) PlaceOrder(ctx context.Context, req PlaceOrderRequest) (*OrderRef, error) {
	if err := validatePlaceOrder(req); err != nil {
		return nil, err
	}
	var result OrderRef
	if _, err := c.executor.Do(ctx, http.MethodPost, "/api/v1/orders", nil, req, &result); err != nil {
		return nil, err
	}
	return &result, nil
}

// PlaceOrderTest validates a Classic Futures order (signature/params only
// — it never reaches the matching engine and cannot be queried
// afterward). Same parameters as PlaceOrder.
//
// Docs: https://www.kucoin.com/docs-new/rest/futures-trading/orders/add-order-test
