// DeactivateDCP disables Disconnect Cancel Protocol. KuCoin has no
// dedicated deactivate endpoint — this is a convenience wrapper around
// SetDCP with Timeout -1.
func (c *Client) DeactivateDCP(ctx context.Context) (*DCPTrigger, error) {
	return c.SetDCP(ctx, SetDCPRequest{Timeout: -1})
}
