// BatchAddOrders submits up to 20 orders in one call, placed sequentially
// by KuCoin. Results (including fills) must be polled or subscribed to —
// this call only confirms placement, not execution.
//
// Docs: https://www.kucoin.com/docs-new/rest/spot-trading/orders/batch-add-orders
func (c *Client) BatchAddOrders(ctx context.Context, orderList []PlaceOrderRequest) ([]BatchOrderResult, error) {
	if len(orderList) > 20 {
		return nil, ErrTooManyBatchOrders
	}
	for _, item := range orderList {
		if err := validatePlaceOrder(item); err != nil {
			return nil, err
		}
	}
	body := struct {
		OrderList []PlaceOrderRequest `json:"orderList"`
	}{OrderList: orderList}
	var result []BatchOrderResult
	if _, err := c.executor.Do(ctx, http.MethodPost, "/api/v1/hf/orders/multi", nil, body, &result); err != nil {
		return nil, err
	}
	return result, nil
}

