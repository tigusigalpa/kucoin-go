// ErrLimitOrderRequiresPrice is returned locally (no network call) when a
// "limit" order request has no price set.
var ErrLimitOrderRequiresPrice = errors.New("kucoin: a limit order requires Price")

// Client provides KuCoin Classic Margin's private order-management
// endpoints. Every method requires credentials; calls return
// transport.ErrCredentialsRequired locally (no network call) if none are
// configured.
type Client struct {
	executor *transport.Executor
}

// NewClient wires an orders.Client to the shared Classic Executor. Not
// normally called directly; use kucoin.NewClient.
func NewClient(executor *transport.Executor) *Client {
	return &Client{executor: executor}
}

func validatePlaceOrder(req PlaceOrderRequest) error {
	if (req.Type == "" || req.Type == "limit") && req.Price == "" {
		return ErrLimitOrderRequiresPrice
	}
	return nil
}

// PlaceOrder submits a new Classic Margin order. req.ClientOid is sent
// as-is (never generated by this SDK) and is required by KuCoin.
//
// Docs: https://www.kucoin.com/docs-new/rest/margin-trading/orders/add-order
func (c *Client) PlaceOrder(ctx context.Context, req PlaceOrderRequest) (*OrderRef, error) {
	if err := validatePlaceOrder(req); err != nil {
		return nil, err
	}
	var result OrderRef
	if _, err := c.executor.Do(ctx, http.MethodPost, "/api/v3/hf/margin/order", nil, req, &result); err != nil {
		return nil, err
	}
	return &result, nil
}

// CancelOrderByID cancels a single order by its KuCoin-assigned ID.
//
// Docs: https://www.kucoin.com/docs-new/rest/margin-trading/orders/cancel-order-by-orderid
func (c *Client) CancelOrderByID(ctx context.Context, orderID, symbol string) (*CancelByOrderIDResult, error) {
	var result CancelByOrderIDResult
	if _, err := c.executor.Do(ctx, http.MethodDelete, "/api/v3/hf/margin/orders/"+orderID, map[string]string{"symbol": symbol}, nil, &result); err != nil {
		return nil, err
	}
	return &result, nil
}

