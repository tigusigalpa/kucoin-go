// CancelAllOrders cancels every open order for a symbol within one trade
// type (cross or isolated). Unlike Classic Spot's account-wide cancel,
// this is scoped to a single symbol/tradeType pair.
//
// Docs: https://www.kucoin.com/docs-new/rest/margin-trading/orders/cancel-all-orders-by-symbol
func (c *Client) CancelAllOrders(ctx context.Context, symbol, tradeType string) (string, error) {
	var result string
	if _, err := c.executor.Do(ctx, http.MethodDelete, "/api/v3/hf/margin/orders", map[string]string{"symbol": symbol, "tradeType": tradeType}, nil, &result); err != nil {
		return "", err
	}
	return result, nil
}

