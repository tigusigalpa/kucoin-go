// GetClosedOrdersOptions are the optional filters for GetClosedOrders.
type GetClosedOrdersOptions struct {
	Side    string // buy, sell
	Type    string // limit, market
	LastID  int64
	Limit   int   // 1-100, default 20
	StartAt int64 // Unix milliseconds
	EndAt   int64 // Unix milliseconds
}

// GetClosedOrders lists historical (filled/cancelled) orders for a
// symbol within one trade type.
//
// Docs: https://www.kucoin.com/docs-new/rest/margin-trading/orders/get-closed-orders
func (c *Client) GetClosedOrders(ctx context.Context, symbol, tradeType string, opts GetClosedOrdersOptions) (*ClosedOrderPage, error) {
	query := map[string]string{"symbol": symbol, "tradeType": tradeType}
	if opts.Side != "" {
		query["side"] = opts.Side
	}
	if opts.Type != "" {
		query["type"] = opts.Type
	}
	if opts.LastID != 0 {
		query["lastId"] = strconv.FormatInt(opts.LastID, 10)
	}
	if opts.Limit > 0 {
		query["limit"] = strconv.Itoa(opts.Limit)
	}
	if opts.StartAt != 0 {
		query["startAt"] = strconv.FormatInt(opts.StartAt, 10)
	}
	if opts.EndAt != 0 {
		query["endAt"] = strconv.FormatInt(opts.EndAt, 10)
	}
	var result ClosedOrderPage
	if _, err := c.executor.Do(ctx, http.MethodGet, "/api/v3/hf/margin/orders/done", query, nil, &result); err != nil {
		return nil, err
	}
	return &result, nil
}

