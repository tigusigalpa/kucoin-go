// Command gendocs regenerates docs/ENDPOINTS.md and docs/CHANNELS.md from
// internal/endpoints.yaml and internal/channels.yaml, the single sources of truth
// for REST and WebSocket coverage. CI runs it and fails the build if the working
// tree then shows a diff, and a unit test performs the same comparison, so the
// coverage documents can never drift from the manifests (and the manifests are
// checked against the code by the root package's manifest tests).
//
// Run: go run ./internal/gendocs
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type endpoint struct {
	Method      string `yaml:"method"`
	AccountMode string `yaml:"account_mode"`
	Domain      string `yaml:"domain"`
	HTTPMethod  string `yaml:"http_method"`
	Path        string `yaml:"path"`
	Access      string `yaml:"access"`
	Permission  string `yaml:"permission"`
	Status      string `yaml:"status"`
	Test        string `yaml:"test"`
	DocURL      string `yaml:"doc_url"`
}

type abandoned struct {
	Method string `yaml:"method"`
	Reason string `yaml:"reason"`
	DocURL string `yaml:"doc_url"`
}

type manifest struct {
	Endpoints []endpoint  `yaml:"endpoints"`
	Abandoned []abandoned `yaml:"abandoned"`
}

type channel struct {
	Session     string `yaml:"session"`
	Method      string `yaml:"method"`
	AccountMode string `yaml:"account_mode"`
	Market      string `yaml:"market"`
	Access      string `yaml:"access"`
	Topic       string `yaml:"topic"`
	Payload     string `yaml:"payload"`
	Status      string `yaml:"status"`
	Test        string `yaml:"test"`
	DocURL      string `yaml:"doc_url"`
}

type notImplemented struct {
	Name   string `yaml:"name"`
	Reason string `yaml:"reason"`
	DocURL string `yaml:"doc_url"`
}

type channelManifest struct {
	Channels       []channel        `yaml:"channels"`
	NotImplemented []notImplemented `yaml:"not_implemented"`
}

func main() {
	if err := run("."); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	endpoints, channels, err := render(root)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, "docs", "ENDPOINTS.md"), []byte(endpoints), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "docs", "CHANNELS.md"), []byte(channels), 0o644)
}

// render builds both documents from the manifests under root.
func render(root string) (endpointsDoc, channelsDoc string, err error) {
	var m manifest
	if err := load(filepath.Join(root, "internal", "endpoints.yaml"), &m); err != nil {
		return "", "", err
	}
	var c channelManifest
	if err := load(filepath.Join(root, "internal", "channels.yaml"), &c); err != nil {
		return "", "", err
	}
	return renderEndpoints(m), renderChannels(c), nil
}

// cell makes text safe inside a Markdown table cell: a pipe would split the cell
// even inside a code span, so every pipe is escaped (once, whether or not the
// manifest already escaped it).
func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(text, `\|`, "|"), "|", `\|`)
}

func load(path string, out any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := yaml.Unmarshal(raw, out); err != nil {
		return fmt.Errorf("parse %s: %w", path, err)
	}
	return nil
}

func renderEndpoints(m manifest) string {
	var b strings.Builder
	b.WriteString("# Endpoint Coverage Map\n\n")
	b.WriteString("Generated from [internal/endpoints.yaml](../internal/endpoints.yaml) by `go run ./internal/gendocs` — do not edit this file by hand, edit the manifest and regenerate. The WebSocket channels are listed in [CHANNELS.md](CHANNELS.md).\n\n")
	b.WriteString("| Method | Account Mode | Domain | HTTP | Path | Access | Permission | Status | Test | Docs |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|\n")
	for _, e := range m.Endpoints {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | `%s` | %s | %s | %s | %s | [Link](%s) |\n",
			cell(e.Method), cell(e.AccountMode), cell(e.Domain), cell(e.HTTPMethod), cell(e.Path), cell(e.Access), cell(e.Permission), cell(e.Status), cell(e.Test), e.DocURL)
	}

	b.WriteString("\n## Not Supported / Abandoned\n\n")
	if len(m.Abandoned) == 0 {
		b.WriteString("None tracked yet. See KuCoin's [abandoned-endpoints introduction](https://www.kucoin.com/docs-new/abandoned-endpoints/introduction) for the platform-wide list.\n")
	} else {
		b.WriteString("| Method | Reason | Docs |\n|---|---|---|\n")
		for _, a := range m.Abandoned {
			fmt.Fprintf(&b, "| `%s` | %s | [Link](%s) |\n", cell(a.Method), cell(a.Reason), a.DocURL)
		}
	}

	b.WriteString("\n## Everything else (not yet implemented)\n\n")
	b.WriteString("Covered: the complete current UTA REST v2 market-data group; the complete public Classic Futures market-data group plus the public funding-rate endpoints; retained UTA REST v1 market/account/orders/positions/leverage compatibility services; Classic Spot market data and high-frequency/stop/OCO/DCP orders; Classic Futures seed orders/positions; Classic Margin market/orders/debit. Every documented WebSocket channel of Classic Futures, Classic Spot, Classic Margin and UTA v2 has a typed subscription (see [CHANNELS.md](CHANNELS.md)). Not yet implemented: most UTA REST v2 account, funding, transfer, withdrawal, sub-account and trading endpoints; the broader Classic account/funding, Futures and Margin Credit surfaces; and specialty domains (Earn, VIP Lending, Convert, Broker, Affiliate and Copy Trading). See [docs/API_COVERAGE.md](API_COVERAGE.md) and the root [README.md](../README.md#status) for the evidence-backed scope.\n")
	return b.String()
}

// sessionTitles gives each session group a readable heading, in display order.
var sessionTitles = []struct{ session, title, access string }{
	{"Classic.Futures.Stream", "Classic Futures", "`client.Classic.Futures.Stream`"},
	{"UTA.V2.Stream", "UTA WebSocket v2", "`client.UTA.V2.Stream`"},
	{"Classic.Spot.Stream", "Classic Spot", "`client.Classic.Spot.Stream`"},
	{"Classic.Margin.Stream", "Classic Margin", "`client.Classic.Margin.Stream`"},
}

func renderChannels(c channelManifest) string {
	var b strings.Builder
	b.WriteString("# WebSocket Channel Coverage\n\n")
	b.WriteString("Generated from [internal/channels.yaml](../internal/channels.yaml) by `go run ./internal/gendocs` — do not edit this file by hand, edit the manifest and regenerate. REST coverage is in [ENDPOINTS.md](ENDPOINTS.md).\n\n")
	b.WriteString("Every row is a typed subscription method on a streaming `Session`: the payload is a Go struct, so applications never parse JSON. The manifest tests (`manifest_test.go`) fail the build if a row does not resolve to a real method, if its test does not exist, or if a `Subscribe…` method exists without a row. See [STREAMING.md](STREAMING.md) for the connection lifecycle, back-pressure and order-book semantics.\n\n")
	seen := map[string]bool{}
	for _, st := range sessionTitles {
		var rows []channel
		for _, ch := range c.Channels {
			if ch.Session == st.session {
				rows = append(rows, ch)
			}
		}
		if len(rows) == 0 {
			continue
		}
		seen[st.session] = true
		fmt.Fprintf(&b, "## %s (%s)\n\n", st.title, st.access)
		b.WriteString("| Method | Market | Access | Topic / channel | Payload | Status | Test | Docs |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|\n")
		for _, ch := range rows {
			fmt.Fprintf(&b, "| `%s` | %s | %s | `%s` | `%s` | %s | %s | [Link](%s) |\n",
				cell(ch.Method), cell(ch.Market), cell(ch.Access), cell(ch.Topic), cell(ch.Payload), cell(ch.Status), cell(ch.Test), ch.DocURL)
		}
		b.WriteString("\n")
	}
	for _, ch := range c.Channels {
		if !seen[ch.Session] {
			fmt.Fprintf(&b, "> Unlisted session group %q: add a title in internal/gendocs.\n", ch.Session)
			seen[ch.Session] = true
		}
	}

	b.WriteString("## Documented by KuCoin but not provided\n\n")
	if len(c.NotImplemented) == 0 {
		b.WriteString("None.\n")
	} else {
		b.WriteString("| Item | Reason | Docs |\n|---|---|---|\n")
		for _, n := range c.NotImplemented {
			fmt.Fprintf(&b, "| %s | %s | [Link](%s) |\n", cell(n.Name), cell(n.Reason), n.DocURL)
		}
	}
	return b.String()
}
